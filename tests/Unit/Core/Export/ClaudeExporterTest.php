<?php

declare(strict_types=1);

namespace ACQC\Tests\Unit\Core\Export;

use ACQC\Core\Export\ClaudeExporter;
use ACQC\Core\Export\ExportResult;
use ACQC\Core\Rules\RuleDefinition;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\TestCase;

#[CoversClass(ClaudeExporter::class)]
#[Group('unit')]
class ClaudeExporterTest extends TestCase
{
    private string $tmpDir;
    private ClaudeExporter $exporter;

    protected function setUp(): void
    {
        $this->tmpDir   = sys_get_temp_dir() . '/acqc_claude_test_' . uniqid();
        mkdir($this->tmpDir, 0755, true);
        $this->exporter = new ClaudeExporter();
    }

    protected function tearDown(): void
    {
        $this->removeDir($this->tmpDir);
    }

    // ── supports() ────────────────────────────────────────────────────────────

    public function testSupportsClaude(): void
    {
        $this->assertTrue($this->exporter->supports('claude'));
    }

    public function testDoesNotSupportOtherTargets(): void
    {
        $this->assertFalse($this->exporter->supports('cursor'));
        $this->assertFalse($this->exporter->supports('sarif'));
    }

    // ── export() — creates CLAUDE.md ──────────────────────────────────────────

    public function testCreatesClaudeMdWhenMissing(): void
    {
        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');

        $this->assertFileExists($this->tmpDir . '/CLAUDE.md');
    }

    public function testNewFileContainsStartMarker(): void
    {
        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('<!-- ACQC RULES START -->', $content);
    }

    public function testNewFileContainsEndMarker(): void
    {
        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('<!-- ACQC RULES END -->', $content);
    }

    public function testNewFileContainsRuleId(): void
    {
        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('AC_DI_001', $content);
    }

    public function testNewFileContainsAutoGeneratedLine(): void
    {
        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('Auto-generated by ACQC', $content);
    }

    public function testExportReturnsClaudeTarget(): void
    {
        $result = $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');

        $this->assertInstanceOf(ExportResult::class, $result);
        $this->assertSame('claude', $result->target);
    }

    public function testExportReturnsClaudeMdPath(): void
    {
        $result = $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');

        $this->assertCount(1, $result->writtenFiles);
        $this->assertStringEndsWith('CLAUDE.md', $result->writtenFiles[0]);
    }

    // ── export() — updates existing CLAUDE.md ────────────────────────────────

    public function testUpdatesExistingClaudeMdWithMarkers(): void
    {
        $originalContent = "# Project Context\n\nSome existing content.\n<!-- ACQC RULES START -->\nOld rules\n<!-- ACQC RULES END -->\n";
        file_put_contents($this->tmpDir . '/CLAUDE.md', $originalContent);

        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $updated = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('# Project Context', $updated, 'Original content must be preserved');
        $this->assertStringContainsString('Some existing content.', $updated, 'Original content must be preserved');
        $this->assertStringContainsString('AC_DI_001', $updated, 'New rules must be injected');
        $this->assertStringNotContainsString('Old rules', $updated, 'Old rule content must be replaced');
    }

    public function testAppendsToExistingClaudeMdWithoutMarkers(): void
    {
        $originalContent = "# Project Context\n\nThis is existing documentation.\n";
        file_put_contents($this->tmpDir . '/CLAUDE.md', $originalContent);

        $this->exporter->export($this->claudeRules(), $this->tmpDir, 'developer');
        $updated = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('# Project Context', $updated, 'Original content must be preserved');
        $this->assertStringContainsString('existing documentation', $updated, 'Original content must be preserved');
        $this->assertStringContainsString('<!-- ACQC RULES START -->', $updated, 'Markers must be appended');
        $this->assertStringContainsString('AC_DI_001', $updated, 'Rules must be appended');
    }

    public function testRulesWithoutClaudePlatformAreExcluded(): void
    {
        $rules = [$this->makeRule('AC_DI_001', 'dependency_injection', ['cli'])]; // no 'claude'
        $this->exporter->export($rules, $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringNotContainsString('AC_DI_001', $content);
    }

    public function testCategoryTitleIsHumanReadable(): void
    {
        $rules = [$this->makeRule('AC_DI_001', 'dependency_injection', ['claude'])];
        $this->exporter->export($rules, $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/CLAUDE.md');

        $this->assertStringContainsString('Dependency Injection', $content);
    }

    // ── check() ───────────────────────────────────────────────────────────────

    public function testCheckReturnsFalseWhenClaudeMdMissing(): void
    {
        $this->assertFalse($this->exporter->check($this->claudeRules(), $this->tmpDir, 'developer'));
    }

    public function testCheckReturnsFalseWhenMarkersAbsent(): void
    {
        file_put_contents($this->tmpDir . '/CLAUDE.md', "# No markers here\n");

        $this->assertFalse($this->exporter->check($this->claudeRules(), $this->tmpDir, 'developer'));
    }

    public function testCheckReturnsTrueWhenContentMatches(): void
    {
        $rules = $this->claudeRules();
        $this->exporter->export($rules, $this->tmpDir, 'developer');

        $this->assertTrue($this->exporter->check($rules, $this->tmpDir, 'developer'));
    }

    public function testCheckReturnsFalseWhenContentIsStale(): void
    {
        $rules = $this->claudeRules();
        $this->exporter->export($rules, $this->tmpDir, 'developer');

        // Alter the CLAUDE.md to simulate stale content
        $current = file_get_contents($this->tmpDir . '/CLAUDE.md');
        file_put_contents($this->tmpDir . '/CLAUDE.md', str_replace('AC_DI_001', 'CHANGED', $current));

        $this->assertFalse($this->exporter->check($rules, $this->tmpDir, 'developer'));
    }

    // ── helpers ────────────────────────────────────────────────────────────────

    /** @return RuleDefinition[] */
    private function claudeRules(): array
    {
        return [$this->makeRule('AC_DI_001', 'dependency_injection', ['claude', 'cli'])];
    }

    private function makeRule(
        string $id,
        string $category,
        array  $platforms = ['claude'],
        array  $roles     = ['developer', 'ci'],
    ): RuleDefinition {
        return RuleDefinition::fromArray([
            'schema_version' => '1.0',
            'id'             => $id,
            'name'           => strtolower(str_replace('_', '-', $id)),
            'title'          => 'Avoid direct ObjectManager usage',
            'description'    => 'Inject dependencies through the constructor instead.',
            'category'       => $category,
            'severity'       => 'warning',
            'tier'           => 3,
            'roles'          => $roles,
            'platforms'      => $platforms,
            'introduced_in'  => '1.0.0',
            'tags'           => [],
            'references'     => [],
            'globs'          => ['**/*.php'],
            'recommendation' => 'Use constructor injection. See DI documentation.',
        ], '');
    }

    private function removeDir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach (scandir($dir) as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }
            $path = $dir . '/' . $item;
            is_dir($path) ? $this->removeDir($path) : unlink($path);
        }
        rmdir($dir);
    }
}
