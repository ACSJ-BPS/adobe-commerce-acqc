import type { RuleCoverageEntry, RuleCoverageStatus } from "./types.js";
import type { Rule } from "@abqc/core";
import { parseCheckSpec } from "./checkers/spec.js";
import { eslintCoveredLibraryIds } from "./eslint-map.js";

const ESLINT_COVERED = eslintCoveredLibraryIds();

export function classifyRules(rules: Rule[]): RuleCoverageEntry[] {
  const ruleIdSet = new Set(rules.map((r) => r.id));
  return rules.map((rule) => ({
    id: rule.id,
    domain: rule.domain,
    title: rule.title,
    severity: rule.severity,
    status: classifyOne(rule, ruleIdSet),
  }));
}

function classifyOne(rule: Rule, ruleIdSet: Set<string>): RuleCoverageStatus {
  if (rule.checkSpec?.trim()) {
    try {
      const check = parseCheckSpec(rule.checkSpec);
      if (check) return "automatable";
    } catch {
      // fall through
    }
  }
  if (ruleIdSet.has(rule.id) && ESLINT_COVERED.has(rule.id)) return "partial";
  return "manual";
}

export function buildCoverageMarkdown(entries: RuleCoverageEntry[]): string {
  const byStatus: Record<RuleCoverageStatus, RuleCoverageEntry[]> = {
    automatable: entries.filter((e) => e.status === "automatable"),
    partial: entries.filter((e) => e.status === "partial"),
    manual: entries.filter((e) => e.status === "manual"),
  };

  const lines: string[] = [
    "# Mechanical rules-check coverage",
    "",
    "Generated by `abqc-rules-check coverage`. Do not edit by hand.",
    "",
    "| Status | Count |",
    "|---|---|",
    `| automatable (has \`### Check\` spec — regex, yaml-path, or builtin) | ${byStatus.automatable.length} |`,
    `| partial (ESLint layer maps to this library rule id) | ${byStatus.partial.length} |`,
    `| manual (requires \`abqc review --ai\` or human review) | ${byStatus.manual.length} |`,
    `| **Total** | **${entries.length}** |`,
    "",
  ];

  for (const status of ["automatable", "partial", "manual"] as RuleCoverageStatus[]) {
    lines.push(`## ${status}`, "");
    const list = byStatus[status] ?? [];
    for (const e of list) {
      lines.push(`- \`${e.id}\` [${e.severity}] — ${e.title}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}
