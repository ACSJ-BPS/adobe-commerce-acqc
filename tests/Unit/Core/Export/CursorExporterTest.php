<?php

declare(strict_types=1);

namespace ACQC\Tests\Unit\Core\Export;

use ACQC\Core\Export\CursorExporter;
use ACQC\Core\Export\ExportResult;
use ACQC\Core\Rules\RuleDefinition;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\TestCase;

#[CoversClass(CursorExporter::class)]
#[Group('unit')]
class CursorExporterTest extends TestCase
{
    private string $tmpDir;
    private CursorExporter $exporter;

    protected function setUp(): void
    {
        $this->tmpDir   = sys_get_temp_dir() . '/acqc_cursor_test_' . uniqid();
        mkdir($this->tmpDir, 0755, true);
        $this->exporter = new CursorExporter();
    }

    protected function tearDown(): void
    {
        $this->removeDir($this->tmpDir);
    }

    // ── supports() ────────────────────────────────────────────────────────────

    public function testSupportsCursor(): void
    {
        $this->assertTrue($this->exporter->supports('cursor'));
    }

    public function testDoesNotSupportOtherTargets(): void
    {
        $this->assertFalse($this->exporter->supports('claude'));
        $this->assertFalse($this->exporter->supports('sarif'));
    }

    // ── export() ──────────────────────────────────────────────────────────────

    public function testExportCreatesRulesDirectory(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');

        $this->assertDirectoryExists($this->tmpDir . '/.cursor/rules');
    }

    public function testExportCreatesMdcFilePerCategory(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');

        $this->assertFileExists($this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc');
    }

    public function testExportReturnsCursorTarget(): void
    {
        $result = $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');

        $this->assertInstanceOf(ExportResult::class, $result);
        $this->assertSame('cursor', $result->target);
    }

    public function testExportReturnsWrittenFiles(): void
    {
        $result = $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');

        $this->assertCount(1, $result->writtenFiles);
    }

    public function testMdcFileContainsFrontmatter(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc');

        $this->assertStringContainsString('---', $content);
        $this->assertStringContainsString('alwaysApply: false', $content);
    }

    public function testMdcFileContainsGeneratedComment(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc');

        $this->assertStringContainsString('Generated by ACQC', $content);
        $this->assertStringContainsString('acqc export cursor', $content);
    }

    public function testMdcFileContainsRuleIdAndTitle(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc');

        $this->assertStringContainsString('AC_DI_001', $content);
        $this->assertStringContainsString('Avoid ObjectManager', $content);
    }

    public function testMdcFileContainsGlobsFromRules(): void
    {
        $this->exporter->export($this->cursorRules(), $this->tmpDir, 'developer');
        $content = file_get_contents($this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc');

        $this->assertStringContainsString('**/*.php', $content);
    }

    public function testRulesWithoutCursorPlatformAreExcluded(): void
    {
        $rules  = [$this->makeRule('AC_SEC_001', 'security', ['cli'])]; // no 'cursor'
        $result = $this->exporter->export($rules, $this->tmpDir, 'developer');

        $this->assertEmpty($result->writtenFiles);
        $this->assertFileDoesNotExist($this->tmpDir . '/.cursor/rules/acqc-security.mdc');
    }

    public function testRulesNotMatchingProfileAreExcluded(): void
    {
        $rules  = [$this->makeRule('AC_DI_001', 'dependency_injection', ['cursor'], ['ci'])];
        $result = $this->exporter->export($rules, $this->tmpDir, 'developer'); // profile=developer, rule only for ci

        $this->assertEmpty($result->writtenFiles);
    }

    public function testMultipleCategoriesCreateMultipleFiles(): void
    {
        $rules = array_merge(
            $this->cursorRules(),
            [$this->makeRule('GL_PHP_001', 'error_handling', ['cursor'])],
        );

        $result = $this->exporter->export($rules, $this->tmpDir, 'developer');
        $this->assertCount(2, $result->writtenFiles);
    }

    // ── check() ───────────────────────────────────────────────────────────────

    public function testCheckReturnsTrueWhenFilesMatch(): void
    {
        $rules = $this->cursorRules();
        $this->exporter->export($rules, $this->tmpDir, 'developer');

        $this->assertTrue($this->exporter->check($rules, $this->tmpDir, 'developer'));
    }

    public function testCheckReturnsFalseWhenFilesMissing(): void
    {
        $this->assertFalse($this->exporter->check($this->cursorRules(), $this->tmpDir, 'developer'));
    }

    public function testCheckReturnsFalseWhenContentIsStale(): void
    {
        $rules = $this->cursorRules();
        $this->exporter->export($rules, $this->tmpDir, 'developer');

        // Overwrite the file with stale content
        file_put_contents(
            $this->tmpDir . '/.cursor/rules/acqc-dependency-injection.mdc',
            'stale content'
        );

        $this->assertFalse($this->exporter->check($rules, $this->tmpDir, 'developer'));
    }

    // ── helpers ────────────────────────────────────────────────────────────────

    /** @return RuleDefinition[] */
    private function cursorRules(): array
    {
        return [$this->makeRule('AC_DI_001', 'dependency_injection', ['cursor', 'cli'])];
    }

    private function makeRule(
        string $id,
        string $category,
        array  $platforms = ['cursor'],
        array  $roles     = ['developer', 'ci'],
    ): RuleDefinition {
        return RuleDefinition::fromArray([
            'schema_version' => '1.0',
            'id'             => $id,
            'name'           => strtolower(str_replace('_', '-', $id)),
            'title'          => 'Avoid ObjectManager',
            'description'    => 'Do not use ObjectManager directly.',
            'category'       => $category,
            'severity'       => 'warning',
            'tier'           => 3,
            'roles'          => $roles,
            'platforms'      => $platforms,
            'introduced_in'  => '1.0.0',
            'tags'           => [],
            'references'     => [],
            'globs'          => ['**/*.php'],
            'recommendation' => 'Use constructor injection instead. See DI documentation.',
            'examples'       => ['bad' => '$om->get(Foo::class);', 'good' => 'public function __construct(Foo $foo)'],
        ], '');
    }

    private function removeDir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach (scandir($dir) as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }
            $path = $dir . '/' . $item;
            is_dir($path) ? $this->removeDir($path) : unlink($path);
        }
        rmdir($dir);
    }
}
