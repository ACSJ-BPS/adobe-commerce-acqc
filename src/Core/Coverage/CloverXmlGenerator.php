<?php

declare(strict_types=1);

namespace ACQC\Core\Coverage;

/**
 * Generates a zero-coverage "baseline" Clover XML file from static analysis
 * alone (no test execution). Every file gets covered*="0" but plausible,
 * non-zero totals, so the report can seed a CI baseline or be merged with
 * real coverage later.
 *
 * The output always carries an "acqc-static-analysis" marker comment so
 * ReportCommand can detect and label baseline files instead of showing a
 * misleading 0% coverage number.
 */
class CloverXmlGenerator
{
    private const BASELINE_MARKER = 'acqc-static-analysis';

    public function generateToFile(string $target, string $cloverOutput, string $projectName, array $excludeList): string
    {
        $files = $this->collectPhpFiles($target, $excludeList);

        $dom = new \DOMDocument('1.0', 'UTF-8');
        $dom->formatOutput = true;
        $dom->appendChild($dom->createComment(' generated by ' . self::BASELINE_MARKER . ' '));

        $coverage = $dom->createElement('coverage');
        $coverage->setAttribute('generated', (string) time());

        $project = $dom->createElement('project');
        $project->setAttribute('name', $projectName);

        $totalStatements = 0;
        $totalMethods = 0;
        $totalElements = 0;

        foreach ($files as $file) {
            [$statements, $methods] = $this->estimateStatementsAndMethods($file);
            $elements = $statements + $methods;

            $fileElement = $dom->createElement('file');
            $fileElement->setAttribute('name', $file);
            $fileElement->appendChild($this->buildMetricsElement($dom, $statements, $methods, $elements));
            $project->appendChild($fileElement);

            $totalStatements += $statements;
            $totalMethods += $methods;
            $totalElements += $elements;
        }

        $project->insertBefore(
            $this->buildMetricsElement($dom, $totalStatements, $totalMethods, $totalElements),
            $project->firstChild
        );

        $coverage->appendChild($project);
        $dom->appendChild($coverage);

        $outputDir = dirname($cloverOutput);
        if (!is_dir($outputDir)) {
            mkdir($outputDir, 0777, true);
        }

        file_put_contents($cloverOutput, $dom->saveXML());

        return $cloverOutput;
    }

    /**
     * @return array{valid: bool, errors: array<int, string>}
     */
    public function validate(string $xmlContent): array
    {
        $errors = [];

        libxml_use_internal_errors(true);
        $xml = simplexml_load_string($xmlContent);

        if ($xml === false) {
            foreach (libxml_get_errors() as $error) {
                $errors[] = trim($error->message);
            }
            libxml_clear_errors();

            return ['valid' => false, 'errors' => $errors ?: ['XML could not be parsed']];
        }

        libxml_clear_errors();

        if ($xml->getName() !== 'coverage') {
            $errors[] = 'Root element must be <coverage>, got <' . $xml->getName() . '>';
        } elseif (!isset($xml->project)) {
            $errors[] = 'Missing required <project> element under <coverage>';
        }

        return ['valid' => count($errors) === 0, 'errors' => $errors];
    }

    private function buildMetricsElement(\DOMDocument $dom, int $statements, int $methods, int $elements): \DOMElement
    {
        $metrics = $dom->createElement('metrics');
        $metrics->setAttribute('statements', (string) $statements);
        $metrics->setAttribute('coveredstatements', '0');
        $metrics->setAttribute('methods', (string) $methods);
        $metrics->setAttribute('coveredmethods', '0');
        $metrics->setAttribute('elements', (string) $elements);
        $metrics->setAttribute('coveredelements', '0');

        return $metrics;
    }

    /**
     * @param array<int, string> $excludeList
     * @return array<int, string>
     */
    private function collectPhpFiles(string $target, array $excludeList): array
    {
        if (!is_dir($target)) {
            return [];
        }

        $files = [];
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($target, \RecursiveDirectoryIterator::SKIP_DOTS)
        );

        foreach ($iterator as $fileInfo) {
            if (!$fileInfo->isFile() || $fileInfo->getExtension() !== 'php') {
                continue;
            }

            $path = $fileInfo->getPathname();

            foreach ($excludeList as $exclude) {
                if ($exclude !== '' && str_contains($path, $exclude)) {
                    continue 2;
                }
            }

            $files[] = $path;
        }

        return $files;
    }

    /**
     * @return array{0: int, 1: int} [estimatedStatements, estimatedMethods]
     */
    private function estimateStatementsAndMethods(string $file): array
    {
        $content = @file_get_contents($file);
        if ($content === false) {
            return [0, 0];
        }

        $statements = 0;
        foreach (explode("\n", $content) as $line) {
            $trimmed = trim($line);
            if ($trimmed === '' || str_starts_with($trimmed, '//') || str_starts_with($trimmed, '#') || str_starts_with($trimmed, '*') || str_starts_with($trimmed, '/*')) {
                continue;
            }
            $statements++;
        }

        $methods = preg_match_all('/\bfunction\s+\w+\s*\(/i', $content);

        return [$statements, $methods !== false ? $methods : 0];
    }
}
