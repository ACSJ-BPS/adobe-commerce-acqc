export function isRegisteredBuiltin(id: string): boolean {
  return id in FILE_BUILTINS || id in REPO_BUILTINS;
}

export function runBuiltinCheck(
  rule: Rule,
  spec: RuleCheck,
  fileCtx: CheckContext | undefined,
  repoCtx: RepoContext | undefined,
): CheckHit[] | Promise<CheckHit[]> {
  const s = spec as BuiltinRuleCheck;
  const repoBuiltin = REPO_BUILTINS[s.id];
  if (repoBuiltin || s.scope === "repo") {
    if (!repoCtx) return [];
    const checker = REPO_BUILTINS[s.id];
    if (!checker) throw new Error(`unknown repo builtin: ${s.id}`);
    return checker.check(repoCtx);
  }

  const checker = FILE_BUILTINS[s.id];
  if (!checker || !fileCtx) return [];
  if (s.files && !matchesFileGlob(fileCtx.filePath, s.files)) return [];
  if (!checker.appliesTo(fileCtx.filePath)) return [];
  const hits = checker.check(fileCtx);
  if (s.id === "unsafe-any-boundary-approx") {
    return filterUnsafeAnyBoundaryHits(hits, rule.id);
  }
  if (s.id === "http-timeout-retry") {
    return filterHttpTimeoutRetryHits(hits, rule.id);
  }
  return hits;
}

/**
 * `http-timeout-retry` is one shared checker referenced by 3 separate
 * markdown rules (set-explicit-timeouts-on-all-outbound-http,
 * wrap-external-http-calls-in-sequences-with-timeouts-retries-with, and
 * apply-circuit-breakers-on-calls-to-external-dependencies) — without this
 * filter, 100% of the circuit-breaker rule's real findings were actually
 * "(timeout)"-tagged missing-timeout hits, because the checker's own
 * retry-loop/circuit-breaker sub-check never got a chance to be the one
 * whose findings were returned; every hit from either sub-check was
 * reported under whichever of the 3 ruleIds happened to be evaluated.
 */
function filterHttpTimeoutRetryHits(hits: CheckHit[] | Promise<CheckHit[]>, ruleId: string): CheckHit[] | Promise<CheckHit[]> {
  const tag = ruleId.endsWith("apply-circuit-breakers-on-calls-to-external-dependencies") ? "(circuit-breaker)" : "(timeout)";
  const filter = (hs: CheckHit[]) => hs.filter((h) => h.message.includes(tag));
  return hits instanceof Promise ? hits.then(filter) : filter(hits);
}

/**
 * `unsafe-any-boundary-approx` is one shared checker referenced by 3 separate
 * markdown rules (no-unsafe-assignment/-call/-member-access, no-unsafe-return,
 * no-unsafe-argument) — it tags each hit's own message with which of the 3
 * conditions it actually matched (the literal "(unsafe-assignment)" /
 * "(unsafe-return)" / "(unsafe-argument)" suffix already embedded by the
 * checker). Without this filter, whichever ruleId happened to be evaluated
 * got the full, unfiltered mixed-cause hit list — misattributing ~2/3 of each
 * rule's findings to the wrong cause.
 */
function filterUnsafeAnyBoundaryHits(hits: CheckHit[] | Promise<CheckHit[]>, ruleId: string): CheckHit[] | Promise<CheckHit[]> {
  const tag = ruleId.endsWith("no-unsafe-return")
    ? "(unsafe-return)"
    : ruleId.endsWith("no-unsafe-argument")
      ? "(unsafe-argument)"
      : "(unsafe-assignment)";
  const filter = (hs: CheckHit[]) => hs.filter((h) => h.message.includes(tag));
  return hits instanceof Promise ? hits.then(filter) : filter(hits);
}

