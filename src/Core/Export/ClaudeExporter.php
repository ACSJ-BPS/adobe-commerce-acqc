<?php

declare(strict_types=1);

namespace ACQC\Core\Export;

use ACQC\Core\Rules\RuleDefinition;

class ClaudeExporter implements ExporterInterface
{
    private const START_MARKER  = '<!-- ACQC RULES START -->';
    private const END_MARKER    = '<!-- ACQC RULES END -->';
    private const ACQC_VERSION  = '3.1.0';

    public function supports(string $target): bool
    {
        return $target === 'claude';
    }

    /** @param RuleDefinition[] $rules */
    public function export(array $rules, string $outputPath, string $profile): ExportResult
    {
        $claudeMdPath = rtrim($outputPath, '/') . '/CLAUDE.md';
        $section      = $this->buildRulesSection($rules, $profile);

        if (file_exists($claudeMdPath)) {
            $existing = file_get_contents($claudeMdPath);
            if (str_contains($existing, self::START_MARKER)) {
                $updated = preg_replace(
                    '~' . preg_quote(self::START_MARKER, '~') . '.*?' . preg_quote(self::END_MARKER, '~') . '~s',
                    $section,
                    $existing,
                );
                file_put_contents($claudeMdPath, $updated);
            } else {
                file_put_contents($claudeMdPath, rtrim($existing) . "\n\n" . $section . "\n");
            }
        } else {
            file_put_contents($claudeMdPath, $section . "\n");
        }

        return new ExportResult('claude', [$claudeMdPath], false);
    }

    /** @param RuleDefinition[] $rules */
    public function check(array $rules, string $outputPath, string $profile): bool
    {
        $claudeMdPath = rtrim($outputPath, '/') . '/CLAUDE.md';

        if (!file_exists($claudeMdPath)) {
            return false;
        }

        $existing = file_get_contents($claudeMdPath);

        if (!str_contains($existing, self::START_MARKER)) {
            return false;
        }

        preg_match(
            '~' . preg_quote(self::START_MARKER, '~') . '.*?' . preg_quote(self::END_MARKER, '~') . '~s',
            $existing,
            $matches,
        );

        $section = $this->buildRulesSection($rules, $profile);

        return isset($matches[0]) && hash('sha256', $matches[0]) === hash('sha256', $section);
    }

    // ── private helpers ────────────────────────────────────────────────────────

    /** @param RuleDefinition[] $rules */
    private function buildRulesSection(array $rules, string $profile): string
    {
        $filtered = array_filter(
            $rules,
            fn(RuleDefinition $r) => in_array('claude', $r->platforms, true)
                && $r->appliesToRole($profile),
        );

        $byCategory = [];
        foreach ($filtered as $rule) {
            $byCategory[$rule->category][] = $rule;
        }

        $lines   = [];
        $lines[] = self::START_MARKER;
        $lines[] = '## ACQC Quality Rules';
        $lines[] = '_Auto-generated by ACQC v' . self::ACQC_VERSION . ' — run `acqc export claude` to regenerate._';

        foreach ($byCategory as $category => $categoryRules) {
            $lines[] = '';
            $title   = ucwords(str_replace('_', ' ', $category));
            $lines[] = "### {$title}";
            foreach ($categoryRules as $rule) {
                $lines[] = "- **{$rule->id}:** {$rule->title} — {$rule->description}";
                $fixSentence = $this->firstSentence($rule->recommendation ?? '');
                if ($fixSentence !== '') {
                    $lines[] = "  - Fix: {$fixSentence}";
                }
            }
        }

        $lines[] = self::END_MARKER;

        return implode("\n", $lines);
    }

    private function firstSentence(string $text): string
    {
        if ($text === '') {
            return '';
        }
        $pos = strpos($text, '.');
        return $pos !== false ? substr($text, 0, $pos + 1) : $text;
    }
}
