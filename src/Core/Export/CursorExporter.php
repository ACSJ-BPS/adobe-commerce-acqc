<?php

declare(strict_types=1);

namespace ACQC\Core\Export;

use ACQC\Core\Rules\RuleDefinition;

class CursorExporter implements ExporterInterface
{
    private const ACQC_VERSION      = '3.1.0';
    private const GENERATED_COMMENT = '<!-- Generated by ACQC v3.1.0 — do not edit directly. Run `acqc export cursor` to regenerate. -->';

    public function supports(string $target): bool
    {
        return $target === 'cursor';
    }

    /** @param RuleDefinition[] $rules */
    public function export(array $rules, string $outputPath, string $profile): ExportResult
    {
        $cursorDir = rtrim($outputPath, '/') . '/.cursor/rules';

        if (!is_dir($cursorDir)) {
            mkdir($cursorDir, 0755, true);
        }

        $filtered    = $this->filterRules($rules, $profile);
        $byCategory  = $this->groupByCategory($filtered);
        $writtenFiles = [];

        foreach ($byCategory as $category => $categoryRules) {
            $filePath = $cursorDir . '/acqc-' . $this->categorySlug($category) . '.mdc';
            file_put_contents($filePath, $this->buildMdcContent($category, $categoryRules));
            $writtenFiles[] = $filePath;
        }

        return new ExportResult('cursor', $writtenFiles, false);
    }

    /** @param RuleDefinition[] $rules */
    public function check(array $rules, string $outputPath, string $profile): bool
    {
        $tmpDir = sys_get_temp_dir() . '/acqc_cursor_check_' . uniqid();
        mkdir($tmpDir, 0755, true);

        try {
            $result = $this->export($rules, $tmpDir, $profile);

            foreach ($result->writtenFiles as $tmpFile) {
                $rel      = '.cursor/rules/' . basename($tmpFile);
                $existing = rtrim($outputPath, '/') . '/' . $rel;

                if (!file_exists($existing)) {
                    return false;
                }

                if (hash_file('sha256', $tmpFile) !== hash_file('sha256', $existing)) {
                    return false;
                }
            }

            // Ensure no extra acqc-*.mdc files exist in the target that we didn't generate
            $targetCursorDir = rtrim($outputPath, '/') . '/.cursor/rules';
            if (is_dir($targetCursorDir)) {
                foreach (glob($targetCursorDir . '/acqc-*.mdc') ?: [] as $existing) {
                    $tmpEquiv = $tmpDir . '/.cursor/rules/' . basename($existing);
                    if (!file_exists($tmpEquiv)) {
                        return false;
                    }
                }
            }
        } finally {
            $this->removeDir($tmpDir);
        }

        return true;
    }

    // ── private helpers ────────────────────────────────────────────────────────

    /** @param RuleDefinition[] $rules */
    private function filterRules(array $rules, string $profile): array
    {
        return array_values(array_filter(
            $rules,
            fn(RuleDefinition $r) => in_array('cursor', $r->platforms, true)
                && $r->appliesToRole($profile),
        ));
    }

    /**
     * @param  RuleDefinition[] $rules
     * @return array<string, RuleDefinition[]>
     */
    private function groupByCategory(array $rules): array
    {
        $grouped = [];
        foreach ($rules as $rule) {
            $grouped[$rule->category][] = $rule;
        }
        return $grouped;
    }

    /** @param RuleDefinition[] $rules */
    private function buildMdcContent(string $category, array $rules): string
    {
        // Collect all unique globs from every rule in the category
        $globMap = [];
        foreach ($rules as $rule) {
            foreach ($rule->globs as $glob) {
                $globMap[$glob] = true;
            }
        }
        $globList = implode(', ', array_keys($globMap)) ?: '"**/*"';

        $lines   = [];
        $lines[] = '---';
        $lines[] = 'description: "ACQC quality rules for ' . $category . '"';
        $lines[] = 'globs: ' . $globList;
        $lines[] = 'alwaysApply: false';
        $lines[] = '---';
        $lines[] = '';
        $lines[] = self::GENERATED_COMMENT;

        foreach ($rules as $rule) {
            $lines[] = '';
            $lines[] = "## {$rule->id}: {$rule->title}";
            $lines[] = '';
            $lines[] = $rule->description;

            if ($rule->examples !== null) {
                if (!empty($rule->examples['bad'])) {
                    $lines[] = '';
                    $lines[] = '**Bad:**';
                    $lines[] = '```';
                    $lines[] = $rule->examples['bad'];
                    $lines[] = '```';
                }
                if (!empty($rule->examples['good'])) {
                    $lines[] = '';
                    $lines[] = '**Good:**';
                    $lines[] = '```';
                    $lines[] = $rule->examples['good'];
                    $lines[] = '```';
                }
            }

            if ($rule->recommendation !== null) {
                $lines[] = '';
                $lines[] = '**Fix:** ' . $rule->recommendation;
            }
        }

        $lines[] = '';

        return implode("\n", $lines);
    }

    private function categorySlug(string $category): string
    {
        return strtolower(str_replace(['_', ' '], '-', $category));
    }

    private function removeDir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach (scandir($dir) as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }
            $path = $dir . '/' . $item;
            is_dir($path) ? $this->removeDir($path) : unlink($path);
        }
        rmdir($dir);
    }
}
